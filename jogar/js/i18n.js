  /* ------------------------------------------------------------ motor */
  function initial() {
    const q = new URLSearchParams(location.search).get('lang');
    if (q && D[q]) return q;
    try {
      const saved = localStorage.getItem(KEY);
      if (saved && D[saved]) return saved;
    } catch {}
    return 'en'; // o idioma principal do jogo
  }

  let lang = initial();
  const listeners = [];
  const info = () => LANGS.find((l) => l.id === lang);

  /** O texto da chave no idioma atual (cai pro inglês se faltar). Aceita {var}. */
  function t(key, vars = {}) {
    const v = D[lang][key] ?? D.en[key];
    if (v === undefined) return key;
    if (typeof v === 'function') return v(vars);
    return v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  }

  /** Aplica as traduções marcadas no HTML. */
  function apply(scope = document) {
    for (const el of scope.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const el of scope.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
    for (const attr of ['alt', 'title', 'aria-label']) {
      for (const el of scope.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)));
    }
    for (const el of scope.querySelectorAll('[data-num]')) {
      const d = Number(el.dataset.dec || 0);
      el.textContent = Number(el.dataset.num).toLocaleString(info().locale, { minimumFractionDigits: d, maximumFractionDigits: d }) + (el.dataset.suffix || '');
    }
    document.documentElement.lang = info().html;
    for (const box of document.querySelectorAll('[data-flags]')) box.innerHTML = flags();
  }

  function flags() {
    return LANGS.map((l) => `<button type="button" class="lang ${l.id === lang ? 'on' : ''}" data-lang="${l.id}" title="${l.name}" aria-label="${l.name}" aria-pressed="${l.id === lang}">` +
      `<svg viewBox="0 0 18 12" width="24" height="16" aria-hidden="true">${FLAGS[l.id]}</svg></button>`).join('');
  }

  function set(id) {
    if (!D[id] || id === lang) return;
    lang = id;
    try { localStorage.setItem(KEY, id); } catch {}
    apply();
    for (const fn of listeners) fn(id);
  }

  document.addEventListener('click', (e) => {
    const b = e.target.closest('[data-lang]');
    if (b) set(b.dataset.lang);
  });

  // estilo das bandeiras (mesmo nas duas páginas)
  const css = document.createElement('style');
  css.textContent = `
    [data-flags] { display: flex; gap: 6px; align-items: center; }
    .lang { padding: 3px; line-height: 0; background: transparent; border: 1px solid transparent; cursor: pointer; opacity: .55; transition: opacity .15s, border-color .15s; }
    .lang svg { display: block; box-shadow: 0 1px 0 rgba(0,0,0,.6); }
    .lang:hover { opacity: .9; }
    .lang.on { opacity: 1; border-color: #D9A441; }
    .lang:focus-visible { outline: 2px solid #F2CE7E; outline-offset: 2px; }`;
  document.head.appendChild(css);

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => apply());
  else apply();

  /** Mais textos (a landpage traz os dela à parte, pra o painel não carregar). */
  function extend(more) {
    for (const [id, dict] of Object.entries(more)) Object.assign(D[id] || (D[id] = {}), dict);
    apply();
  }

  root.I18N = {
    t, apply, set, flags, extend, LANGS,
    lang: () => lang,
    locale: () => info().locale,
    onChange: (fn) => listeners.push(fn),
  };
